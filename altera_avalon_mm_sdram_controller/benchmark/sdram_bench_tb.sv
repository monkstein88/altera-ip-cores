`timescale 1ns/1ps
// =============================================================================
// sdram_bench_tb.sv
//
// Benchmark harness: traffic generator -> controller under test -> Intel's
// functional SDRAM model, with a JEDEC timing checker bound to the memory bus.
//
// Prints one row per access pattern: cycles, bytes, MB/s, and percentage of
// the theoretical bus limit. The point is that two controllers can be run
// through the identical stimulus and compared on numbers.
//
// THE MEMORY MODEL DOES NOT ENFORCE TIMING
// ----------------------------------------
// Intel's model decodes commands and returns data; it ignores tRCD, tRP, tRC,
// tRAS, tWR and the refresh interval. Data integrity against it therefore
// proves the controller addresses memory correctly and nothing about whether
// it is driving the part legally. sdram_timing_check.sv is what covers that,
// and its violation count is reported alongside the throughput so a "fast"
// result that got there illegally cannot pass unnoticed.
//
// DUT SELECTION
// -------------
// `DUT_MODULE is the controller's module name. It defaults to the incumbent
// Intel controller as generated by qsys. A replacement controller with the
// same legacy az_/za_ slave port can be dropped in by overriding it.
// =============================================================================

`ifndef DUT_MODULE
  `define DUT_MODULE sdram_mem_ctrl
`endif

module sdram_bench_tb;

    // ---------------- configuration ----------------
    localparam int  CLK_KHZ  = 100_000;          // 100 MHz
    localparam real CLK_NS   = 1_000_000.0 / real'(CLK_KHZ);
    localparam int  ADDR_W   = 25;               // word address, 32M x 16
    localparam int  DATA_W   = 16;
    localparam int  N_OPS    = 4096;             // per pattern

    // Theoretical ceiling: one 16-bit word per clock.
    localparam real PEAK_MBPS = (real'(CLK_KHZ) * 1000.0 * real'(DATA_W) / 8.0)
                                / 1_000_000.0;

    logic clk = 0, reset_n = 0;
    always #(CLK_NS/2.0) clk = ~clk;

    // ---------------- generator <-> controller ----------------
    logic [ADDR_W-1:0]   az_addr;
    logic [DATA_W/8-1:0] az_be_n;
    logic                az_cs, az_rd_n, az_wr_n;
    logic [DATA_W-1:0]   az_data, za_data;
    logic                za_valid, za_waitrequest;

    // ---------------- controller <-> memory ----------------
    logic [12:0] zs_addr;
    logic [1:0]  zs_ba;
    logic        zs_cas_n, zs_cke, zs_cs_n, zs_ras_n, zs_we_n;
    logic [1:0]  zs_dqm;
    wire  [15:0] zs_dq;

    logic        start;
    logic [3:0]  pattern;
    logic        prime;
    logic        busy, done;
    logic [31:0] cycles, ops_issued, ops_retired, errors;

    sdram_traffic_gen #(.ADDR_W(ADDR_W), .DATA_W(DATA_W)) gen (
        .clk(clk), .reset_n(reset_n),
        .start(start), .pattern(pattern), .prime(prime), .n_ops(N_OPS), .base_addr('0),
        .busy(busy), .done(done), .cycles(cycles),
        .ops_issued(ops_issued), .ops_retired(ops_retired), .errors(errors),
        .az_addr(az_addr), .az_be_n(az_be_n), .az_cs(az_cs), .az_data(az_data),
        .az_rd_n(az_rd_n), .az_wr_n(az_wr_n),
        .za_data(za_data), .za_valid(za_valid), .za_waitrequest(za_waitrequest));

    `DUT_MODULE dut (
        .az_addr(az_addr), .az_be_n(az_be_n), .az_cs(az_cs), .az_data(az_data),
        .az_rd_n(az_rd_n), .az_wr_n(az_wr_n), .clk(clk), .reset_n(reset_n),
        .za_data(za_data), .za_valid(za_valid), .za_waitrequest(za_waitrequest),
        .zs_addr(zs_addr), .zs_ba(zs_ba), .zs_cas_n(zs_cas_n), .zs_cke(zs_cke),
        .zs_cs_n(zs_cs_n), .zs_dq(zs_dq), .zs_dqm(zs_dqm),
        .zs_ras_n(zs_ras_n), .zs_we_n(zs_we_n));

    sdram_mem_model mem (
        .clk(clk),
        .zs_addr(zs_addr), .zs_ba(zs_ba), .zs_cas_n(zs_cas_n), .zs_cke(zs_cke),
        .zs_cs_n(zs_cs_n), .zs_dq(zs_dq), .zs_dqm(zs_dqm),
        .zs_ras_n(zs_ras_n), .zs_we_n(zs_we_n));

    sdram_timing_check #(.CLK_KHZ(CLK_KHZ)) tchk (
        .clk(clk), .reset_n(reset_n), .cke(zs_cke), .cs_n(zs_cs_n),
        .ras_n(zs_ras_n), .cas_n(zs_cas_n), .we_n(zs_we_n),
        .ba(zs_ba), .addr(zs_addr));

    // ---------------- run one pattern ----------------
    int unsigned tot_err;
    real         mbps, pct;

    task automatic run(input logic [3:0] p, input string name);
        begin
            // Prime: same addresses, all writes, not timed. A read pattern
            // must find known contents or the integrity check is meaningless.
            @(posedge clk); prime <= 1'b1; start <= 1'b1; pattern <= p;
            @(posedge clk); start <= 1'b0;
            wait (done);
            @(posedge clk); prime <= 1'b0;
            repeat (4) @(posedge clk);

            // Measure.
            @(posedge clk); start <= 1'b1; pattern <= p;
            @(posedge clk); start <= 1'b0;
            wait (done);
            @(posedge clk);

            // bytes moved / elapsed time
            mbps = (real'(N_OPS) * real'(DATA_W) / 8.0)
                   / ((real'(cycles) * CLK_NS) / 1000.0);   // B/us == MB/s
            pct  = 100.0 * mbps / PEAK_MBPS;
            tot_err += errors;

            $display("  %-14s %8d %9d %10.1f %7.1f%%   %s",
                     name, cycles, N_OPS * DATA_W/8, mbps, pct,
                     (errors == 0) ? "data ok" : $sformatf("%0d DATA ERRORS", errors));
        end
    endtask

    initial begin
        start = 0; pattern = 0; prime = 0; tot_err = 0;
        repeat (8) @(posedge clk);
        reset_n = 1;

        // The controller must finish its power-on sequence (200 us NOP, mode
        // register, refreshes) before any of this means anything.
        #250_000;

        $display("");
        $display("=========================================================================");
        $display(" SDRAM controller benchmark   %0d ops/pattern   %0d MHz   %0d-bit bus",
                 N_OPS, CLK_KHZ/1000, DATA_W);
        $display(" theoretical peak: %.1f MB/s", PEAK_MBPS);
        $display("=========================================================================");
        $display("  pattern          cycles     bytes      MB/s   of peak   integrity");
        $display("  -------------------------------------------------------------------");

        // Fill the region first so the read patterns have known contents.
        run(4'd0, "seq write");
        run(4'd1, "seq read");
        run(4'd2, "seq read/write");
        run(4'd3, "same-row rd/wr");
        run(4'd4, "bank stride");
        run(4'd5, "random");

        $display("  -------------------------------------------------------------------");
        $display("  data errors: %0d      timing violations: %0d",
                 tot_err, tchk.errs);
        $display("=========================================================================");
        $display("");

        if (tot_err != 0 || tchk.errs != 0) begin
            $display(" *** BENCHMARK INVALID - see errors above ***");
            $fatal(1);
        end
        $display(" benchmark complete");
        $finish;
    end

    initial begin
        #50_000_000;
        $display("watchdog: benchmark did not finish");
        $fatal(1);
    end

endmodule
