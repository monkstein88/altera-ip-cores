`timescale 1ns/1ps
// =============================================================================
// sdram_bench_tb.sv
//
// Benchmark harness: traffic generator -> controller under test -> SDRAM
// device model, with a JEDEC timing checker bound to the memory bus.
//
// Prints one row per access pattern: cycles, bytes, MB/s, and percentage of
// the theoretical bus limit. The point is that two controllers can be run
// through the identical stimulus and compared on numbers.
//
// THE MEMORY MODEL DOES NOT ENFORCE TIMING
// ----------------------------------------
// sdram_device_model.sv decodes commands, tracks a row per bank and returns
// data; it ignores tRCD, tRP, tRC, tRAS, tWR and the refresh interval. Data
// integrity against it therefore proves the controller addresses memory
// correctly and nothing about whether it is driving the part legally.
// sdram_timing_check.sv is what covers that, and its violation count is
// reported alongside the throughput so a "fast" result that got there
// illegally cannot pass unnoticed.
//
// DUT SELECTION
// -------------
// `DUT_MODULE is the controller's module name. It defaults to INTEL'S CORE
// (`sdram_mem_ctrl`, as generated by qsys). Override it to measure THE CUSTOM
// CORE (`avalon_mm_sdram_controller`) or any other controller with the same
// legacy az_/za_ slave port.
// =============================================================================

`ifndef DUT_MODULE
  `define DUT_MODULE sdram_mem_ctrl
`endif

module sdram_bench_tb #(
    // Which part to drive. 0 is the DE10-Lite's ISSI IS42S16320D-7, which is
    // what the published comparison against Intel's core is measured on; 1 is
    // the DE0-Nano's IS42S16160B-7.
    //
    // These figures are the same ones the Platform Designer presets carry, and
    // doc/tools/check_facts.py holds the two copies to each other - the .qprs
    // is the source, this is a copy, and a copy nobody checks is how a
    // datasheet number drifts.
    parameter int PART = 0
);

    // ---------------- configuration ----------------
    localparam int  CLK_KHZ  = 100_000;          // 100 MHz
    localparam real CLK_NS   = 1_000_000.0 / real'(CLK_KHZ);
    // Both controllers are measured at CAS 3, which is what both parts run at.
    // The timing checker needs it too: the read-to-write turnaround it enforces
    // is CAS_LAT+1.
    localparam int  CAS_LAT  = 3;
    localparam int  DATA_W   = 16;
    localparam int  N_OPS    = 4096;             // per pattern

    // ---- the part ----------------------------------------------------------
    //   PART 0  ISSI IS42S16320D-7      DE10-Lite, 64 MByte, 10-bit column
    //   PART 1  ISSI IS42S16160B-7      DE0-Nano,  32 MByte,  9-bit column
    //   PART 2  Micron MT48LC4M16A2-75  no board,   8 MByte,  8-bit column
    //
    // Part 2 is on no board here. It is in the table because it is the only
    // one of the three with a different ROW count and a different refresh
    // period - 4,096 rows in 64 ms rather than 8,192 - so it is what stops
    // the geometry handling from being fitted to two parts that happen to
    // share it. Its figures come from the Micron datasheet, not from a board.
    localparam int  ROW_BITS  = (PART == 2) ? 12 : 13;
    localparam int  BANK_BITS = 2;               // all three parts
    localparam int  SA_BITS   = (PART == 2) ? 12 : 13;
    localparam int  COL_BITS  = (PART == 1) ? 9 : (PART == 2) ? 8 : 10;
    localparam int  ADDR_W    = ROW_BITS + COL_BITS + BANK_BITS;

    // Rows to refresh, and the period they must all be refreshed within.
    localparam int  REF_ROWS_P      = (PART == 2) ? 4096 : 8192;
    localparam int  REF_PERIOD_MS_P = 64;        // all three parts

    // Timings, picoseconds, from each part's datasheet at CAS 3.
    localparam int  T_RC_PS   = (PART == 1) ? 67_500 : (PART == 2) ? 66_000 : 60_000;
    localparam int  T_RAS_PS  = (PART == 1) ? 45_000 : (PART == 2) ? 44_000 : 37_000;
    localparam int  T_RP_PS   = (PART == 1) ? 20_000 : (PART == 2) ? 20_000 : 15_000;
    localparam int  T_RCD_PS  = (PART == 1) ? 20_000 : (PART == 2) ? 20_000 : 15_000;
    localparam int  T_RRD_PS  = (PART == 1) ? 14_000 : (PART == 2) ? 15_000 : 14_000;
    localparam int  T_WR_PS   = (PART == 1) ? 14_000 : (PART == 2) ? 15_000 : 14_000;
    localparam int  T_MRD_PS  = (PART == 1) ? 15_000 : (PART == 2) ? 20_000 : 14_000;
    localparam int  T_RFC_PS  = (PART == 1) ? 67_500 : (PART == 2) ? 66_000 : 60_000;

    localparam string PART_NAME =
        (PART == 1) ? "ISSI IS42S16160B-7  DE0-Nano 32 MByte" :
        (PART == 2) ? "Micron MT48LC4M16A2-75  no board, 8 MByte" :
                      "ISSI IS42S16320D-7  DE10-Lite 64 MByte";

    // Theoretical ceiling: one 16-bit word per clock.
    localparam real PEAK_MBPS = (real'(CLK_KHZ) * 1000.0 * real'(DATA_W) / 8.0)
                                / 1_000_000.0;

    logic clk = 0, reset_n = 0;
    always #(CLK_NS/2.0) clk = ~clk;

    // ---------------- generator <-> controller ----------------
    logic [ADDR_W-1:0]   az_addr;
    logic [DATA_W/8-1:0] az_be_n;
    logic                az_cs, az_rd_n, az_wr_n;
    logic [DATA_W-1:0]   az_data, za_data;
    logic                za_valid, za_waitrequest;

    // ---------------- controller <-> memory ----------------
    logic [12:0] zs_addr;
    logic [1:0]  zs_ba;
    logic        zs_cas_n, zs_cke, zs_cs_n, zs_ras_n, zs_we_n;
    logic [1:0]  zs_dqm;
    wire  [15:0] zs_dq;

    logic        start;
    logic [3:0]  pattern;
    logic        prime;
    logic        busy, done;
    logic [31:0] cycles, ops_issued, ops_retired, errors;

    sdram_traffic_gen #(.ADDR_W(ADDR_W), .DATA_W(DATA_W),
                        .ROW_BITS(ROW_BITS), .COL_BITS(COL_BITS)) gen (
        .clk(clk), .reset_n(reset_n),
        .start(start), .pattern(pattern), .prime(prime), .n_ops(N_OPS), .base_addr('0),
        .busy(busy), .done(done), .cycles(cycles),
        .ops_issued(ops_issued), .ops_retired(ops_retired), .errors(errors),
        .az_addr(az_addr), .az_be_n(az_be_n), .az_cs(az_cs), .az_data(az_data),
        .az_rd_n(az_rd_n), .az_wr_n(az_wr_n),
        .za_data(za_data), .za_valid(za_valid), .za_waitrequest(za_waitrequest));

    `DUT_MODULE dut (
        .az_addr(az_addr), .az_be_n(az_be_n), .az_cs(az_cs), .az_data(az_data),
        .az_rd_n(az_rd_n), .az_wr_n(az_wr_n), .clk(clk), .reset_n(reset_n),
        .za_data(za_data), .za_valid(za_valid), .za_waitrequest(za_waitrequest),
        .zs_addr(zs_addr), .zs_ba(zs_ba), .zs_cas_n(zs_cas_n), .zs_cke(zs_cke),
        .zs_cs_n(zs_cs_n), .zs_dq(zs_dq), .zs_dqm(zs_dqm),
        .zs_ras_n(zs_ras_n), .zs_we_n(zs_we_n));

    // Look-ahead is a parameter of the custom core and does not exist on
    // Intel's, so it cannot be a parameter of this testbench without breaking
    // the other DUT. `defparam` under an ifdef reaches into the instance only
    // when asked, which keeps one port map for both cores. Build with
    // -DDUT_LOOKAHEAD=0 to turn it off.
    //
    // The look-ahead table in README.md is produced this way. Before this
    // there was no supported way to reproduce it at all.
    // (A comment line may not begin with the simulator's name - it is read as
    //  a pragma - which is why the flag is quoted inline above.)
`ifdef DUT_LOOKAHEAD
    defparam dut.LOOKAHEAD = `DUT_LOOKAHEAD;
`endif

    // The part's geometry and timings, reaching into the instance the same way
    // and for the same reason: Intel's core has neither these parameter names
    // nor picosecond timings, so this cannot be a parameter of the instance
    // without breaking the other DUT. Only needed away from the defaults, so
    // it is guarded rather than always applied.
`ifdef DUT_PART
    defparam dut.ROW_BITS  = ROW_BITS;
    defparam dut.COL_BITS  = COL_BITS;
    defparam dut.BANK_BITS = BANK_BITS;
    defparam dut.SA_BITS   = SA_BITS;
    defparam dut.ADDR_W    = ADDR_W;
    defparam dut.T_RC_PS   = T_RC_PS;
    defparam dut.T_RAS_PS  = T_RAS_PS;
    defparam dut.T_RP_PS   = T_RP_PS;
    defparam dut.T_RCD_PS  = T_RCD_PS;
    defparam dut.T_RRD_PS  = T_RRD_PS;
    defparam dut.T_WR_PS   = T_WR_PS;
    defparam dut.T_MRD_PS  = T_MRD_PS;
    defparam dut.T_RFC_PS  = T_RFC_PS;
    // A 4,096-row part must be refreshed half as often as an 8,192-row one.
    // Left at the default this was merely conservative rather than wrong,
    // which is exactly the kind of thing that never gets noticed.
    defparam dut.REF_ROWS      = REF_ROWS_P;
    defparam dut.REF_PERIOD_MS = REF_PERIOD_MS_P;
`endif

    sdram_device_model #(
        .DATA_BITS(DATA_W), .ROW_BITS(ROW_BITS), .COL_BITS(COL_BITS),
        .BANK_BITS(BANK_BITS), .SA_BITS(SA_BITS)
    ) mem (
        .clk(clk),
        .zs_addr(zs_addr), .zs_ba(zs_ba), .zs_cas_n(zs_cas_n), .zs_cke(zs_cke),
        .zs_cs_n(zs_cs_n), .zs_dq(zs_dq), .zs_dqm(zs_dqm),
        .zs_ras_n(zs_ras_n), .zs_we_n(zs_we_n));

    sdram_timing_check #(
        .CLK_KHZ(CLK_KHZ), .CAS_LAT(CAS_LAT),
        .T_RC_NS (real'(T_RC_PS ) / 1000.0), .T_RAS_NS(real'(T_RAS_PS) / 1000.0),
        .T_RP_NS (real'(T_RP_PS ) / 1000.0), .T_RCD_NS(real'(T_RCD_PS) / 1000.0),
        .T_RRD_NS(real'(T_RRD_PS) / 1000.0), .T_WR_NS (real'(T_WR_PS ) / 1000.0),
        .T_MRD_NS(real'(T_MRD_PS) / 1000.0), .T_RFC_NS(real'(T_RFC_PS) / 1000.0),
        // The refresh geometry has to follow the part too. Left at the
        // checker's 8192-row default, a 4,096-row part is held to twice the
        // refresh rate it actually needs and the checker reports a violation
        // the controller did not commit. Both ISSI parts here have 8,192
        // rows, so nothing exposed that until a part with 4,096 was added.
        .REF_ROWS(REF_ROWS_P), .REF_PERIOD_MS(real'(REF_PERIOD_MS_P))
    ) tchk (
        .clk(clk), .reset_n(reset_n), .cke(zs_cke), .cs_n(zs_cs_n),
        .ras_n(zs_ras_n), .cas_n(zs_cas_n), .we_n(zs_we_n),
        .ba(zs_ba), .addr(zs_addr));

    // ---------------- run one pattern ----------------
    int unsigned tot_err;
    real         mbps, pct;

    task automatic run(input logic [3:0] p, input string name);
        begin
            // Prime: same addresses, all writes, not timed. A read pattern
            // must find known contents or the integrity check is meaningless.
            @(posedge clk); prime <= 1'b1; start <= 1'b1; pattern <= p;
            @(posedge clk); start <= 1'b0;
            wait (done);
            @(posedge clk); prime <= 1'b0;
            repeat (4) @(posedge clk);

            // Measure.
            @(posedge clk); start <= 1'b1; pattern <= p;
            @(posedge clk); start <= 1'b0;
            wait (done);
            @(posedge clk);

            // bytes moved / elapsed time
            mbps = (real'(N_OPS) * real'(DATA_W) / 8.0)
                   / ((real'(cycles) * CLK_NS) / 1000.0);   // B/us == MB/s
            pct  = 100.0 * mbps / PEAK_MBPS;
            tot_err += errors;

            $display("  %-16s %8d %9d %10.1f %7.1f%%   %s",
                     name, cycles, N_OPS * DATA_W/8, mbps, pct,
                     (errors == 0) ? "data ok" : $sformatf("%0d DATA ERRORS", errors));
        end
    endtask

    initial begin
        start = 0; pattern = 0; prime = 0; tot_err = 0;
        repeat (8) @(posedge clk);
        reset_n = 1;

        // The controller must finish its power-on sequence (200 us NOP, mode
        // register, refreshes) before any of this means anything.
        #250_000;

        $display("");
        $display("=========================================================================");
        $display(" SDRAM controller benchmark   %0d ops/pattern   %0d MHz   %0d-bit bus",
                 N_OPS, CLK_KHZ/1000, DATA_W);
        $display(" part: %s", PART_NAME);
        // Name the DUT in the RESULTS BANNER, not only in run_bench.sh's
        // startup line. The two cores produce tables of the same shape, and a
        // table read without its surrounding output is unattributable - which
        // is how Intel's 21.9 MB/s got mistaken for this core's 78.9 while
        // checking that a change had not altered any cycle count. The default
        // DUT is Intel's, so the bare `./run_bench.sh` measures the core being
        // replaced, exactly as benchmark/README.md says and exactly contrary
        // to what someone in a hurry assumes.
`ifdef DUT_PART
        $display(" DUT : %s  (this project's core)", `"`DUT_MODULE`");
`else
        $display(" DUT : %s  (the core being replaced)", `"`DUT_MODULE`");
`endif
        $display(" theoretical peak: %.1f MB/s", PEAK_MBPS);
        $display("=========================================================================");
        $display("  pattern            cycles     bytes      MB/s   of peak   integrity");
        $display("  -------------------------------------------------------------------");

        // Fill the region first so the read patterns have known contents.
        run(4'd0, "seq write");
        run(4'd1, "seq read");
        run(4'd2, "seq read/write");
        run(4'd3, "same-row rd/wr");
        run(4'd4, "bank+row walk");
        run(4'd6, "4-bank same row");
        run(4'd5, "random");

        $display("  -------------------------------------------------------------------");
        $display("  data errors: %0d      timing violations: %0d",
                 tot_err, tchk.errs);
        $display("=========================================================================");
        $display("");

        if (tot_err != 0 || tchk.errs != 0) begin
            $display(" *** BENCHMARK INVALID - see errors above ***");
            $fatal(1);
        end
        $display(" benchmark complete");
        $finish;
    end

    initial begin
        #50_000_000;
        $display("watchdog: benchmark did not finish");
        $fatal(1);
    end

endmodule
